def gunshot(dur, body_f, crack, low, tail, thump_f=(140, 45), bright=1.0):
    n = noise(dur)
    crack_part = hp(n, 1800) * env_exp(dur, crack) * bright
    body = lp(n, body_f) * env_exp(dur, crack * 3.5)
    thump = sweep(thump_f[0], thump_f[1], dur) * env_exp(dur, low)
    click = np.zeros(int(dur * SR))
    click[:60] = np.hanning(120)[60:] * 1.0
    x = mix(crack_part * 0.9, body * 1.1, thump * 0.9, click * 0.5)
    x = dist(x, 2.2)
    return reverb(x, tail, 0.22, 5000)


def mech_click(f=3200, dur=0.04, level=1.0):
    t = t_axis(dur)
    ping = np.sin(2 * np.pi * f * t) * np.exp(-t / 0.006)
    n = hp(noise(dur), 2500) * np.exp(-t / 0.003)
    return (ping * 0.6 + n) * level


