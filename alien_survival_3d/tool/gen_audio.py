def notes(seq, shape='sine', dec=0.15, gap=0.07, d=None):
    total = d or (len(seq) * gap + dec * 4)
    buf = np.zeros(int(total * SR))
    for i, f in enumerate(seq):
        nd = dec * 4
        x = tone(f, nd, shape) * env_exp(nd, dec)
        place(buf, x, i * gap)
    return buf


