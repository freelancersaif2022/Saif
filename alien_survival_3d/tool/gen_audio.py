def explosion(dur=2.6, f=900, sub=(70, 28)):
    n = noise(dur)
    body = lp(n, f) * env_exp(dur, 0.45, 0.004)
    crack = hp(n, 2000) * env_exp(dur, 0.04)
    boom = sweep(sub[0], sub[1], dur) * env_exp(dur, 0.5)
    crackle = (rng.random(int(dur * SR)) > 0.9985) * rng.uniform(-1, 1, int(dur * SR))
    crackle = hp(crackle, 1500) * env_exp(dur, 0.8)
    x = mix(body * 1.2, crack * 0.6, boom * 1.3, crackle * 1.5)
    return reverb(dist(x, 2.5), 1.8, 0.3, 2500)


