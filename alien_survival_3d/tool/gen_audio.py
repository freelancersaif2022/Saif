def formant(x, freqs, q=6):
    out = np.zeros_like(x)
    for f, g in freqs:
        out += bp(x, f * (1 - 1 / q), f * (1 + 1 / q)) * g
    return out


def growl(dur, f0, f1, rough=0.5, formants=((350, 1.0), (900, 0.6), (2400, 0.25)), vibr=7):
    t = t_axis(dur)
    f = f0 * (f1 / f0) ** (t / dur) * (1 + 0.04 * np.sin(2 * np.pi * vibr * t) + 0.03 * lp(noise(dur), 20) * 8)
    ph = 2 * np.pi * np.cumsum(f) / SR
    src = 2 * ((ph / (2 * np.pi)) % 1) - 1
    src = src * (1 - rough) + bp(noise(dur), 100, 3000) * rough
    src *= 1 + 0.5 * np.sin(2 * np.pi * 23 * t)  # flutter
    v = formant(src, formants)
    v *= adsr(len(v), 0.05, 0.2, 0.8, dur * 0.35)
    return reverb(dist(v * 2, 2), 0.7, 0.2)


