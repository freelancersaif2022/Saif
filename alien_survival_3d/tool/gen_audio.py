def bird(seed):
    r = np.random.default_rng(seed)
    d = 1.6
    buf = np.zeros(int(d * SR))
    at = 0.05
    for _ in range(r.integers(3, 7)):
        cd = r.uniform(0.05, 0.14)
        f0 = r.uniform(2500, 4200)
        f1 = f0 * r.uniform(0.6, 1.5)
        c = sweep(f0, f1, cd) * np.sin(np.pi * t_axis(cd) / cd) ** 2
        c *= 1 + 0.3 * np.sin(2 * np.pi * 60 * t_axis(cd))
        place(buf, c, at)
        at += cd + r.uniform(0.03, 0.12)
        if at > d - 0.2:
            break
    return reverb(buf, 1.2, 0.3)


