def midi(n):
    return 440.0 * 2 ** ((n - 69) / 12)


def synth(freq, dur, kind='saw', cutoff=2000, a=0.01, d=0.1, s=0.7, r=0.2, detune=0.0):
    n = int(dur * SR)
    voices = [0.0] if not detune else [-detune, 0, detune]
    x = np.zeros(n)
    for dv in voices:
        x += sweep(freq * (1 + dv), freq * (1 + dv) * 1.0000001, dur, kind, 'lin')
    x /= len(voices)
    x = lp(x, cutoff)
    return x * adsr(n, a, d, s, min(r, dur * 0.5))


def kick(dur=0.35):
    return sweep(150, 42, dur) * env_exp(dur, 0.12) + lp(noise(dur), 2000) * env_exp(dur, 0.005) * 0.3


def snare(dur=0.25):
    return bp(noise(dur), 1500, 7000) * env_exp(dur, 0.06) * 0.8 + tone(190, dur) * env_exp(dur, 0.04) * 0.5


def hat(dur=0.06, open_=False):
    return hp(noise(dur if not open_ else 0.25), 7000) * env_exp(dur if not open_ else 0.25, 0.015 if not open_ else 0.08) * 0.35


def tom(f=110, dur=0.4):
    return sweep(f * 1.5, f, dur) * env_exp(dur, 0.12)


def music_menu():
    bpm = 84
    beat = 60 / bpm
    bars = 12
    total = bars * 4 * beat
    buf = np.zeros(int((total + 3) * SR))
    prog = [(57, [57, 60, 64]), (53, [53, 57, 60]), (48, [48, 52, 55]), (55, [55, 59, 62])]  # Am F C G
    for b in range(bars):
        root, chord = prog[b % 4]
        start = b * 4 * beat
        pad = sum(synth(midi(n + 12), 4 * beat + 0.4, 'saw', 1400, 0.6, 0.4, 0.7, 0.8, 0.004) for n in chord) / 3
        place(buf, pad * 0.35, start)
        place(buf, synth(midi(root - 12), 4 * beat, 'tri', 600, 0.05, 0.2, 0.8, 0.3) * 0.45, start)
        arp = [chord[0] + 24, chord[1] + 24, chord[2] + 24, chord[1] + 24]
        for i in range(8):
            place(buf, synth(midi(arp[i % 4]), beat * 0.5, 'square', 2200, 0.005, 0.15, 0.2, 0.1) * 0.12, start + i * beat * 0.5)
        if b >= 4:
            for k in (0, 2):
                place(buf, kick() * 0.5, start + k * beat)
            for k in range(8):
                place(buf, hat() * (0.6 if k % 2 else 0.3), start + k * beat * 0.5)
    buf = reverb(buf, 2.2, 0.3, 3500)
    return loopify(buf[:int((total + 1.0) * SR)], 1.0)


def music_combat():
    bpm = 124
    beat = 60 / bpm
    bars = 16
    total = bars * 4 * beat
    buf = np.zeros(int((total + 2) * SR))
    bass_line = [40, 40, 52, 40, 43, 40, 47, 45]  # E minor ostinato (8ths)
    prog = [[52, 55, 59], [48, 52, 55], [50, 53, 57], [47, 50, 54]]  # Em C D Bm
    for b in range(bars):
        start = b * 4 * beat
        for i in range(8):
            n = bass_line[i] + (0 if b % 4 != 3 else -2)
            place(buf, synth(midi(n), beat * 0.48, 'saw', 900, 0.003, 0.08, 0.6, 0.05) * 0.5, start + i * beat * 0.5)
        for k in range(4):
            place(buf, kick() * 0.9, start + k * beat)
        for k in (1, 3):
            place(buf, snare() * 0.7, start + k * beat)
        for k in range(8):
            place(buf, hat(open_=(k == 7)) * (0.8 if k % 2 else 0.5), start + k * beat * 0.5)
        chord = prog[(b // 2) % 4]
        if b >= 4:
            for k in range(4):
                stab = sum(synth(midi(n + 12), beat * 0.25, 'saw', 3000, 0.002, 0.06, 0.3, 0.05, 0.006) for n in chord) / 3
                place(buf, stab * 0.22, start + k * beat + beat * 0.5)
        if b >= 8:
            lead = [64, 67, 71, 69, 67, 64, 62, 64]
            for i, n in enumerate(lead):
                place(buf, synth(midi(n + 12), beat * 0.45, 'square', 2600, 0.01, 0.1, 0.5, 0.1) * 0.1, start + i * beat * 0.5)
        if b % 4 == 3:
            for k in range(4):
                place(buf, tom(130 - k * 15) * 0.5, start + 3 * beat + k * beat * 0.25)
    buf = reverb(buf, 1.2, 0.18, 5000)
    return loopify(buf[:int((total + 0.6) * SR)], 0.6)


def music_boss():
    bpm = 146
    beat = 60 / bpm
    bars = 16
    total = bars * 4 * beat
    buf = np.zeros(int((total + 2) * SR))
    riff = [38, 38, 41, 38, 44, 38, 43, 41]
    for b in range(bars):
        start = b * 4 * beat
        for i in range(8):
            n = riff[i] + (3 if b % 4 == 2 else 0)
            x = synth(midi(n), beat * 0.48, 'saw', 1400, 0.002, 0.05, 0.8, 0.04, 0.01)
            place(buf, dist(x * 2.5, 3) * 0.32, start + i * beat * 0.5)
        for k in range(8):
            place(buf, kick() * 0.85, start + k * beat * 0.5)
        for k in (1, 3):
            place(buf, snare() * 0.8, start + k * beat)
        for k in range(16):
            place(buf, hat() * 0.4, start + k * beat * 0.25)
        if b % 2 == 0:
            brass = sum(synth(midi(n), beat * 1.5, 'saw', 1800, 0.05, 0.2, 0.7, 0.3, 0.005) for n in (50, 53, 57)) / 3
            place(buf, brass * 0.35, start)
            place(buf, sum(synth(midi(n), beat * 1.5, 'saw', 1800, 0.05, 0.2, 0.7, 0.3, 0.005) for n in (49, 53, 56)) / 3 * 0.35, start + 2 * beat)
    buf = reverb(buf, 1.4, 0.2, 4000)
    return loopify(buf[:int((total + 0.6) * SR)], 0.6)


def music_gameover():
    beat = 60 / 60
    buf = np.zeros(int(9 * SR))
    for i, chord in enumerate([[57, 60, 64], [53, 57, 60], [52, 55, 59], [45, 52, 57]]):
        x = sum(synth(midi(n), beat * 2.2, 'saw', 1200, 0.3, 0.4, 0.6, 1.0, 0.004) for n in chord) / 3
        place(buf, x * 0.5, i * beat * 1.6)
        place(buf, synth(midi(chord[0] - 12), beat * 2.2, 'tri', 500, 0.1, 0.3, 0.7, 1.0) * 0.4, i * beat * 1.6)
    return reverb(buf, 3.0, 0.4, 3000)


